"""LinkLibrarian — a multi-agent AI bookmark manager.

Six agents work together on every link you save (see the agents/ folder):
Librarian (manager) → Scout → Reader → Summariser → Tagger → Quality Checker.

Run locally:  python app.py
"""

import logging

from flask import Flask, render_template

from config import Config, get_config
from database import init_db
from routes import api, pages
from utils.helpers import configure_logging

logger = logging.getLogger(__name__)


def create_app(config_class: type[Config] | None = None) -> Flask:
    """Application factory."""
    configure_logging()

    app = Flask(__name__)
    app.config.from_object(config_class or get_config())

    init_db(app)

    app.register_blueprint(pages)
    app.register_blueprint(api)

    register_error_handlers(app)
    register_template_filters(app)

    announce_agents()

    if not Config.ai_enabled():
        logger.warning(
            "GROQ_API_KEY is not set. Links will still save, but summaries and tags "
            "will be generated by a basic offline heuristic. "
            "Copy .env.example to .env and add your free key from console.groq.com."
        )
    return app


def announce_agents() -> None:
    """Print the agent team in the terminal when the server starts."""
    from services.link_service import librarian

    logger.info("LinkLibrarian agent team on duty:")
    for agent in librarian.team:
        logger.info("   • %-22s %s", agent.name, agent.role)


def register_error_handlers(app: Flask) -> None:
    """Friendly HTML pages for the common failure codes."""

    @app.errorhandler(404)
    def not_found(_error):
        return render_template("404.html"), 404

    @app.errorhandler(500)
    def server_error(error):  # pragma: no cover - defensive
        logger.error("Server error: %s", error)
        return render_template("500.html"), 500


def register_template_filters(app: Flask) -> None:
    """Jinja filters used by the templates."""

    @app.template_filter("shortdate")
    def shortdate(value):
        return value.strftime("%d %b %Y") if value else ""

    @app.template_filter("domain")
    def domain(url: str):
        from urllib.parse import urlparse

        return urlparse(url).netloc.replace("www.", "")


app = create_app()

if __name__ == "__main__":
    app.run(host=Config.HOST, port=Config.PORT, debug=Config.DEBUG)
